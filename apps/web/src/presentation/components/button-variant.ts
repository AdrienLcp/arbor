/**
 * How a button or a button-shaped link looks:
 * - `'primary'` — the one main action of a view, solid
 * - `'ghost'` — a second action, outlined
 * - `'cover'` — the main action on the vermilion cover, inverted and taller
 * - `'link'` — a secondary path, underlined text with an icon
 */
export type ButtonVariant = 'cover' | 'ghost' | 'link' | 'primary'
